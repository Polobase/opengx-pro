def c_bytes(data, indent="    ", per_line=16):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) for i in range(0, len(data), per_line)]
    return ",\n".join(indent + r for r in rows)


def c_string(codes):
    """Bytes -> C string literal body: ASCII as is (\\, " and ? escaped), others as octal escapes."""
    out = []
    for c in codes:
        if c in (0x22, 0x5C, 0x3F):
            out.append("\\" + chr(c))
        elif 0x20 <= c <= 0x7E:
            out.append(chr(c))
        else:
            out.append(f"\\{c:03o}")
    return "".join(out)


def _local(symbol):
    return "k_" + symbol[3:] if symbol.startswith("nx_") else "k_" + symbol


def _char_comment(code):
    if 0x20 <= code <= 0x7E:
        return "' '" if code == 0x20 else f"'{chr(code)}'" if chr(code) not in "*/\\" else f"0x{code:02X}"
    if code >= strings.EXTRA_BASE:
        return strings.EXTRA_NAMES[code - strings.EXTRA_BASE]
    return f"0x{code:02X}"


def font_c(table, title, icon_names=None):
    """C definition of one nx_font_t with its data, records and extra-code list."""
    k = _local(table.name)
    out = [f"/* ---- {title} ---- */"]
    out.append(f"static const uint8_t {k}_data[{len(table.data)}] = {{\n{c_bytes(table.data)}\n}};")
    out.append(f"static const nx_glyph_t {k}_glyphs[{len(table.records)}] = {{")
    codes = list(range(table.first, table.last + 1)) + table.extras
    for i, (off, w, h, x, y, adv) in enumerate(table.records):
        label = icon_names[i] if icon_names else _char_comment(codes[i])
        out.append(f"    {{ 0x{off:04X}u, {w}, {h}, {x}, {y}, {adv}, 0 }},   /* {label} */")
    out.append("};")
    extra = "NULL"
    if table.extras:
        out.append(f"static const uint8_t {k}_extra[{len(table.extras)}] = {{ "
                   + ", ".join(f"0x{c:02X}" for c in table.extras) + " };")
        extra = f"{k}_extra"
    out.append(f"const nx_font_t {table.name} = {{ {table.height}, {table.baseline}, {table.bpp}, "
               f"0x{table.first:02X}, 0x{table.last:02X}, {len(table.extras)}, {{ 0, 0 }}, "
               f"{extra}, {k}_glyphs, {k}_data }};")
    return "\n".join(out) + "\n"


def str_ids_h(ids, texts_en):
    out = [BANNER + " */\n", "#pragma once", "", "/* UI strings (assets/nx/strings/<lang>.json), in source order. */",
           "enum nx_str_id {"]
    for sid, codes in zip(ids, texts_en):
        shown = c_string(codes).replace("*/", "* /").replace("/*", "/ *")
        out.append(f"    {strings.c_ident(sid)},   /* \"{shown}\" */")
    out += ["    NX_STR_COUNT", "};", ""]
    return "\n".join(out)


def assets_h(fonts, iconsets, pal, str_langs, total, max_bytes, qrs=()):
    """fonts: [(cfg, table)]; iconsets: [(cfg, table)]; pal: (themes, tokens, values); qrs: [QrTable]."""
    out = [BANNER + NOTICE, "#pragma once", "", "#include <stdint.h>", "", '#include "nx_asset_fmt.h"',
           '#include "nx_str_ids.h"', "",
           f"#define NX_ASSET_BYTES {total}u   /* all tables in nx_assets.c (tool budget report) */",
           f"#define NX_ASSET_MAX {max_bytes}u", "",
           "/* String codes of the extra characters of the text fonts (HTML entity names). */"]
    for i, name in enumerate(strings.EXTRA_NAMES):
        out.append(f"#define NX_CH_{name} 0x{strings.EXTRA_BASE + i:02X}u   /* {strings.EXTRA_CHARS[i]} */")
    out += ["", "/* Fonts */"]
    for cfg, t in fonts:
        out.append(f"extern const nx_font_t {t.name};   /* {cfg['id']}: {cfg['file']} {cfg['size']} px */")
    for cfg, t in iconsets:
        out += ["", f"/* Icons, {cfg['size']} px box ({cfg['bpp']} bpp): glyph codes of {t.name} */", "enum {"]
        for icon in cfg["icons"]:
            out.append(f"    {cfg['prefix']}{icon['id'].upper()},")
        out += [f"    {cfg['prefix']}COUNT", "};", f"extern const nx_font_t {t.name};"]
    themes, tokens, _ = pal
    out += ["", "/* Palettes: nx_palettes[theme][token] in RGB565 */", "enum {"]
    out += [f"    NX_THEME_{th.upper()}," for th in themes] + ["    NX_THEME_COUNT", "};", "enum {"]
    out += [f"    NX_PAL_{tok.upper()}," for tok in tokens] + ["    NX_PAL_COUNT", "};"]
    out.append("extern const uint16_t nx_palettes[NX_THEME_COUNT][NX_PAL_COUNT];")
    out += ["", "/* Strings: nx_str_pool + nx_str_off[lang][id] is a NUL-terminated string */", "enum {"]
    out += [f"    NX_LANG_{lang.upper()}," for lang in str_langs] + ["    NX_LANG_COUNT", "};"]
    out += ["extern const uint16_t nx_str_off[NX_LANG_COUNT][NX_STR_COUNT];", "extern const char nx_str_pool[];"]
    if qrs:
        out += ["", "/* QR codes (assets/nx/qr.json): N x N modules; N rows of (N + 7) / 8 bytes, top to bottom, most",
                " * significant bit first, 1 = dark */"]
    for q in qrs:
        out.append(f"#define {q.ident}_N {q.n}u   /* \"{q.text}\", {q.label} */")
        out.append(f"extern const uint8_t {q.name}[{q.ident}_N * (({q.ident}_N + 7u) / 8u)];")
    out.append("")
    return "\n".join(out)


def assets_c(fonts, iconsets, pal, str_langs, offsets, pool, pool_owner, qrs=()):
    out = [BANNER + NOTICE, "#include <stddef.h>", "", '#include "nx_assets.h"', "",
           '_Static_assert(NX_ASSET_BYTES <= NX_ASSET_MAX, "nx assets exceed NX_ASSET_MAX");', ""]
    for cfg, t in fonts:
        out.append(font_c(t, f"{cfg['id']}: {cfg['file']} {cfg['size']} px, {cfg['bpp']} bpp"))
    for cfg, t in iconsets:
        names = [f"{cfg['prefix']}{i['id'].upper()}" for i in cfg["icons"]]
        out.append(font_c(t, f"{t.name}: {cfg['size']} px icons, {cfg['bpp']} bpp", names))
    themes, tokens, values = pal
    out.append("/* ---- palettes (assets/nx/palettes.json) ---- */")
    out.append("const uint16_t nx_palettes[NX_THEME_COUNT][NX_PAL_COUNT] = {")
    for th in themes:
        row = ", ".join(f"0x{values[th][tok]:04X}u" for tok in tokens)
        out.append(f"    {{ {row} }},   /* {th} */")
    out.append("};\n")
    out.append("/* ---- strings (assets/nx/strings/<lang>.json), identical texts and tails stored once ---- */")
    out.append("const char nx_str_pool[] =")
    start = 0
    while start < len(pool):
        end = pool.index(b"\0", start)
        term = ";" if end + 1 == len(pool) else ""
        out.append(f"    \"{c_string(pool[start:end])}\\0\"{term}   /* {pool_owner[start]} */")
        start = end + 1
    out.append("const uint16_t nx_str_off[NX_LANG_COUNT][NX_STR_COUNT] = {")
    for lang in str_langs:
        out.append(f"    {{   /* {lang} */")
        offs = offsets[lang]
        for i in range(0, len(offs), 12):
            out.append("        " + ", ".join(str(o) for o in offs[i:i + 12]) + ",")
        out.append("    },")
    out.append("};\n")
    for q in qrs:
        out.append(f"/* ---- QR code \"{q.text}\" ({q.label}; assets/nx/qr.json) ---- */")
        out.append(f"const uint8_t {q.name}[{q.ident}_N * (({q.ident}_N + 7u) / 8u)] = {{\n"
                   f"{c_bytes(q.blob(), per_line=q.row_bytes)}\n}};\n")
    return "\n".join(out)


def vectors_h(sel_glyphs, widths, fits, strs, fmt, pals, qrs=()):
    """Host-test goldens. sel_glyphs: [(symbol, label, code, Glyph, rle)]; widths: [(symbol, codes, w)];
    fits: [(symbol, codes, max_px, n, w, ell)]; strs: [(lang_idx, id_ident, codes)];
    fmt: (id_ident, [arg bytes], expected bytes); pals: [(theme_idx, token_idx, value)]."""
    out = ["/* Generated by tools/gen_nx_assets.py: expected results of src/nx/nx_font.c for the",
           " * committed tables. The alpha goldens come from the rendered images, not from the encoder",
           " * output. Do not edit. */", "#pragma once", "", "#include <stdint.h>", "",
           '#include "nx/nx_assets.h"', "",
           "typedef struct {", "    const nx_font_t *font;", "    const char *what;", "    uint8_t code, w, h;",
           "    int8_t x_off;", "    uint8_t y_off, advance, rle;", "    const uint8_t *alpha;", "} vec_glyph_t;",
           "typedef struct {", "    const nx_font_t *font;", "    const char *text;", "    uint16_t width;",
           "} vec_width_t;",
           "typedef struct {", "    const nx_font_t *font;", "    const char *text;",
           "    uint16_t max_px, n, width;", "    uint8_t ellipsis;", "} vec_fit_t;",
           "typedef struct {", "    uint8_t lang;", "    uint16_t id;", "    const char *text;", "} vec_str_t;",
           "typedef struct {", "    uint8_t theme, token;", "    uint16_t rgb565;", "} vec_pal_t;", ""]
    for i, (_, _, _, g, _) in enumerate(sel_glyphs):
        out.append(f"static const uint8_t vec_alpha_{i}[{max(1, len(g.px))}] = {{\n{c_bytes(g.px or [0])}\n}};")
    out.append("static const vec_glyph_t k_vec_glyphs[] = {")
    for i, (sym, label, code, g, rle) in enumerate(sel_glyphs):
        out.append(f"    {{ &{sym}, \"{label}\", 0x{code:02X}, {g.w}, {g.h}, {g.x_off}, {g.y_off}, "
                   f"{g.advance}, {1 if rle else 0}, vec_alpha_{i} }},")
    out += ["};", "static const vec_width_t k_vec_widths[] = {"]
    for sym, codes, w in widths:
        out.append(f"    {{ &{sym}, \"{c_string(codes)}\", {w} }},")
    out += ["};", "static const vec_fit_t k_vec_fits[] = {"]
    for sym, codes, mx, n, w, ell in fits:
        out.append(f"    {{ &{sym}, \"{c_string(codes)}\", {mx}, {n}, {w}, {ell} }},")
    out += ["};", "static const vec_str_t k_vec_strs[] = {"]
    for lang, ident, codes in strs:
        out.append(f"    {{ {lang}, {ident}, \"{c_string(codes)}\" }},")
    out += ["};"]
    ident, args, expected = fmt
    out.append(f"#define VEC_FMT_ID {ident}")
    out.append("static const char *const k_vec_fmt_args[" + str(len(args)) + "] = { "
               + ", ".join(f"\"{c_string(a)}\"" for a in args) + " };")
    out.append(f"#define VEC_FMT_EXPECTED \"{c_string(expected)}\"")
    out.append("static const vec_pal_t k_vec_pals[] = {")
    for th, tok, v in pals:
        out.append(f"    {{ {th}, {tok}, 0x{v:04X}u }},")
    out += ["};"]
    for q in qrs:   # dark modules of each QR code
        out.append(f"#define VEC_{q.ident[3:]}_DARK {q.dark()}")
    out.append("")
    return "\n".join(out)


def table_sizes(fonts, iconsets, pal, pool, offsets, qrs=()):
    """Bytes per table as they land in flash (Cortex-M0+: 4-byte pointers)."""
    sizes = {}
    for _, t in fonts + iconsets:
        sizes[t.name] = t.size_bytes()
    themes, tokens, _ = pal
    sizes["nx_palettes"] = 2 * len(themes) * len(tokens)
    sizes["nx_str_pool"] = len(pool) + 1       # the literal's own terminating NUL
    sizes["nx_str_off"] = 2 * sum(len(o) for o in offsets.values())
    for q in qrs:
        sizes[q.name] = q.size_bytes()
    return sizes
