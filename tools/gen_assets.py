#!/usr/bin/env python3
"""Generate assets.c/assets.h from the user's own copy of the original firmware.

The vendor's fonts and bitmaps are not part of this repository. The build extracts them
from original/GxDisplayFW.bin (v7789) using the addresses documented in docs/spec/display.md §8.

Every font and image of the catalogue is extracted, byte for byte as the original stores it,
except the four goodbye-screen images: the original keeps them as u16 arrays with only the low
byte used (all high bytes are zero), so only the low bytes are kept (1 byte per 8 pixels, the
same bit order and polarity).

Usage: gen_assets.py <GxDisplayFW.bin> <output dir>
"""

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gxfw  # noqa: E402

EXPECTED_SHA256 = "69455ac4327fc1c51a99054eaa56c6fc48346a60132c8dfaea74a2899c59d894"

# name, address, length in output bytes, stride (2 = u16 array, low byte used), docs/spec/display.md §8
ASSETS = [
    # fonts and glyph tables (records keep their code byte, and the width byte for proportional fonts)
    ("font_ui24", 0x080135A5, 86 * 50, 1),            # {code, width, 48 B}, 24 px
    ("font_freq24", 0x08014671, 18 * 50, 1),          # {code, width, 48 B}, frequency digits
    ("font_gnum_16x22", 0x0801264F, 2 * 45, 1),       # {code, 44 B}: '1' "G1", '2' "G2"
    ("font_out_24x44", 0x080149F5, 2 * 133, 1),       # {code, 132 B}: '1' "Out1", '2' "Out2"
    ("icons_status_48x51", 0x08012F7D, 4 * 307, 1),   # {code, 306 B}: 'c' 'r' 'p' 's'
    # single images (the code byte in front of each is not used by the drawing code)
    ("bmp_boot_ghost_logo", 0x080129B0, 0x460, 1),
    ("bmp_red2_small", 0x080126AA, 0x2A, 1),
    ("bmp_boot_welcome", 0x080126D5, 0x27C, 1),
    ("bmp_red2_large", 0x0801295A, 0x42, 1),
    ("bmp_boot_tagline", 0x08012E11, 0x16C, 1),
    ("bmp_usb_icon", 0x0801344A, 0x42, 1),
    ("bmp_sync_icon", 0x0801357D, 0x20, 1),
    ("bmp_bye_qrcode", 0x08014B00, 0x415, 2),
    ("bmp_bye_logo", 0x0801532A, 0xF0, 2),
    ("bmp_bye_text", 0x0801550A, 0x306, 2),
    ("bmp_bye_url", 0x08015B16, 0x124, 2),
    ("bmp_unused_waveforms", 0x08015D5E, 0x3C0, 1),   # not referenced by the original code
]
DEFINES = {
    "ASSET_FONT_UI24_RECORDS": 86,
    "ASSET_FONT_FREQ24_RECORDS": 18,
    "ASSET_FONT_GNUM_RECORDS": 2,
    "ASSET_FONT_OUT_RECORDS": 2,
    "ASSET_ICONS_STATUS_RECORDS": 4,
}
# code bytes of the fixed-size tables: (asset, record size, expected codes)
CODES = [
    ("font_gnum_16x22", 45, b"12"),
    ("font_out_24x44", 133, b"12"),
    ("icons_status_48x51", 307, b"crps"),
]


def main() -> int:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    raw = src.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        sys.exit(f"{src}: unexpected firmware (sha256 {digest}); the asset addresses are for v7789 only")
    plain, _ = gxfw.decode(raw)

    extracted = {}
    for name, addr, length, stride in ASSETS:
        start = addr - gxfw.LOAD_ADDRESS
        data = plain[start:start + length * stride]
        if stride == 2:
            if any(data[1::2]):
                sys.exit(f"{name}: u16 image with a non-zero high byte")
            data = data[0::2]
        extracted[name] = data
    for name, size, codes in CODES:
        found = bytes(extracted[name][i * size] for i in range(len(codes)))
        if found != codes:
            sys.exit(f"{name}: unexpected record codes {found!r}")

    header = ["/* Generated by tools/gen_assets.py from the original firmware. Do not edit or commit. */",
              "#pragma once", "#include <stdint.h>", ""]
    header += [f"#define {k} {v}u" for k, v in DEFINES.items()] + [""]
    body = ['#include "assets.h"', ""]
    for name, _, length, _ in ASSETS:
        data = extracted[name]
        header.append(f"extern const uint8_t asset_{name}[{length}];")
        rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, length, 16)]
        body.append(f"const uint8_t asset_{name}[{length}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n")

    out.mkdir(parents=True, exist_ok=True)
    (out / "assets.h").write_text("\n".join(header) + "\n")
    (out / "assets.c").write_text("\n".join(body))
    print(f"assets: {len(ASSETS)} items, {sum(a[2] for a in ASSETS)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
