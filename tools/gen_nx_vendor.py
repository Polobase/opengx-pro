#!/usr/bin/env python3
"""Generate the Spooky2 boot splash for the nx firmware from the user's own original image.

The splash of the original (docs/spec/display.md §9: ghost logo, red "2", "Welcome to Spooky",
red "2", tagline) is rendered as its five 1-bit blits draw it on the portrait panel (window rows
of x0..x1 from y0, MSB first, 0-bits painted black), turned to the landscape screen (X = 319 - y,
Y = x) and written as one 1-bit mask per blit: the pixels of its colour that no later blit paints
over. The output goes into the build directory only: it is vendor artwork and never committed.

Usage: gen_nx_vendor.py <GxDisplayFW.bin> <output dir>   (writes nx_vendor.c)
"""

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_assets  # noqa: E402
import gxfw  # noqa: E402

WHITE, RED = 1, 2
# (x0, x1, y0, asset, colour): src/classic/ui.c ui_draw_boot_splash, in drawing order
BLITS = [
    (0x1E, 0x8D, 0x78, "bmp_boot_ghost_logo", WHITE),
    (0x1E, 0x35, 0x83, "bmp_red2_small", RED),
    (0xAD, 0xC4, 0x32, "bmp_boot_welcome", WHITE),
    (0xAE, 0xC5, 0x1E, "bmp_red2_large", RED),
    (200, 0xD7, 0x3C, "bmp_boot_tagline", WHITE),
]


def main() -> int:
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    raw = src.read_bytes()
    if hashlib.sha256(raw).hexdigest() != gen_assets.EXPECTED_SHA256:
        sys.exit(f"{src}: unexpected firmware; the splash addresses are for v7789 only")
    plain, _ = gxfw.decode(raw)
    assets = {name: plain[addr - gxfw.LOAD_ADDRESS:addr - gxfw.LOAD_ADDRESS + length]
              for name, addr, length, stride in gen_assets.ASSETS if stride == 1}

    canvas = {}   # (X, Y) landscape -> colour; black pixels are absent
    windows = []  # landscape boxes (X0, Y0, X1, Y1), inclusive
    for x0, x1, y0, name, colour in BLITS:
        w = x1 - x0 + 1
        data = assets[name]
        n = len(data) * 8
        rows = n // w
        for k in range(rows * w):
            px, py = x0 + k % w, y0 + k // w
            X, Y = 319 - py, px
            if data[k >> 3] & (0x80 >> (k & 7)):
                canvas[(X, Y)] = colour
            else:
                canvas.pop((X, Y), None)
        windows.append((319 - (y0 + rows - 1), x0, 319 - y0, x1))

    body = ["/* Generated by tools/gen_nx_vendor.py from the user's original image. Vendor artwork:",
            " * do not edit or commit. */", '#include "nx/nx_vendor.h"', ""]
    entries = []
    for i, ((X0, Y0, X1, Y1), (_, _, _, name, colour)) in enumerate(zip(windows, BLITS)):
        later = windows[i + 1:]
        w, h = X1 - X0 + 1, Y1 - Y0 + 1
        stride = (w + 7) // 8
        bits = bytearray(stride * h)
        for Y in range(Y0, Y1 + 1):
            for X in range(X0, X1 + 1):
                if canvas.get((X, Y)) != colour:
                    continue
                if any(a <= X <= c and b <= Y <= d for a, b, c, d in later):
                    continue   # a later blit paints this pixel
                i_ = (Y - Y0) * stride + (X - X0) // 8
                bits[i_] |= 0x80 >> ((X - X0) & 7)
        rows = [", ".join(f"0x{b:02X}" for b in bits[j:j + 16]) for j in range(0, len(bits), 16)]
        body.append(f"static const uint8_t k_{name}[{len(bits)}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n")
        entries.append(f"    {{ {X0}, {Y0}, {w}, {h}, {1 if colour == RED else 0}, k_{name} }},")
    body.append("const struct nx_vmask k_nx_vendor_splash[NX_VENDOR_SPLASH_N] = {")
    body += entries
    body.append("};")
    out.mkdir(parents=True, exist_ok=True)
    (out / "nx_vendor.c").write_text("\n".join(body) + "\n")
    print(f"nx_vendor: {len(BLITS)} masks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
